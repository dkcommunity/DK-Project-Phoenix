CREATE TABLE IF NOT EXISTS SpeedGuardLog (
  ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  PlayerID VARCHAR(32) NOT NULL DEFAULT '',
  Name VARCHAR(64) NOT NULL DEFAULT '',
  IP VARCHAR(45) NOT NULL DEFAULT '',
  Channel VARCHAR(16) NOT NULL,
  PacketTime BIGINT UNSIGNED NOT NULL DEFAULT 0,
  BaseTime INT NOT NULL DEFAULT 0,
  DiffTime INT NOT NULL DEFAULT 0,
  ErrorTime INT NOT NULL DEFAULT 0,
  SampleCount INT UNSIGNED NOT NULL DEFAULT 0,
  MaxPerSecond INT UNSIGNED NOT NULL DEFAULT 0,
  HighRate TINYINT UNSIGNED NOT NULL DEFAULT 0,
  AbusePoint INT NOT NULL DEFAULT 0,
  ViolationCount BIGINT UNSIGNED NOT NULL DEFAULT 0,
  ServerGroupID INT UNSIGNED NOT NULL DEFAULT 0,
  ZoneID INT UNSIGNED NOT NULL DEFAULT 0,
  XCoord INT UNSIGNED NOT NULL DEFAULT 0,
  YCoord INT UNSIGNED NOT NULL DEFAULT 0,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ID),
  KEY IDX_SpeedGuardLog_PlayerID (PlayerID, CreatedAt),
  KEY IDX_SpeedGuardLog_IP (IP, CreatedAt),
  KEY IDX_SpeedGuardLog_Channel (Channel, CreatedAt),
  KEY IDX_SpeedGuardLog_CreatedAt (CreatedAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
